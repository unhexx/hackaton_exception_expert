"""Симуляционная валидация механики тестирования (ТЗ §2, §3.4, критерий оценки 2).

Пакет не зависит от веб-приложения. Кабинет использует его сборку варианта и
оценку через ``product/matching/assessment.py`` — симуляция проверяет тот же код.
Состав:

- ``scale``       — шкала уровня и границы грейдов;
- ``irt``         — модель ответа (IRT, 3 параметра) и оценка уровня по ответам;
- ``bank``        — банк семейств вопросов (изоморфные варианты, сложность);
- ``candidates``  — 500 синтетических кандидатов с известным «истинным» грейдом;
- ``form``        — сборка индивидуального варианта теста по единому плану;
- ``scoring``     — оценка ответов и решение по грейду;
- ``responders``  — поведение кандидатов: честно, наугад, «всегда b», утечка и т.д.;
- ``baseline``    — модель текущего теста проекта (3 вопроса, ключ b-c-a);
- ``simulate``    — цепочка попыток и расчёт показателей;
- ``adaptive``    — улучшенная механика v2: уверенность, доп. блоки у границы,
                    накопление между попытками, пилот, осторожный порог;
- ``generate`` / ``run`` / ``plot`` — командные точки входа.

Только стандартная библиотека Python 3.10+. Графики (``plot``) — опционально,
им нужен matplotlib.
"""
